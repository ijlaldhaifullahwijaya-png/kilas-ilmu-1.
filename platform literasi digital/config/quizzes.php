$buildQuiz = static function (string $title, string $icon, string $description, array $questions): array {
    $items = [];
    foreach ($questions as $index => [$prompt, $options, $answer, $explanation]) {
        $items['q'.($index + 1)] = compact('prompt', 'options', 'answer', 'explanation');
